from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.errors import ForbiddenError, NotFoundError
from app.core.pagination import Page, PageParams
from app.db.models.audit import AuditLog
from app.db.models.workspace import WorkspaceMember
from app.policies.access import can_view_audit_logs


async def record_audit_event(
    db: AsyncSession,
    *,
    workspace_id: uuid.UUID,
    actor_id: uuid.UUID,
    action: str,
    resource_type: str,
    resource_id: uuid.UUID,
    metadata: dict[str, Any] | None = None,
    ip_address: str | None = None,
    user_agent: str | None = None,
) -> AuditLog:
    """Record an immutable append-only audit event."""
    audit = AuditLog(
        workspace_id=workspace_id,
        actor_id=actor_id,
        action=action,
        resource_type=resource_type,
        resource_id=resource_id,
        ip_address=ip_address,
        user_agent=user_agent,
        metadata_json=metadata or {},
    )
    db.add(audit)
    await db.flush()
    return audit


async def list_workspace_audit_logs(
    db: AsyncSession,
    *,
    workspace_id: uuid.UUID,
    actor_id: uuid.UUID,
    pagination: PageParams,
    filter_actor_id: uuid.UUID | None = None,
    filter_action: str | None = None,
    filter_resource_type: str | None = None,
    date_from: datetime | None = None,
    date_to: datetime | None = None,
) -> Page[AuditLog]:
    """List audit events for a workspace. Accessible only by workspace owners and admins."""
    stmt_member = select(WorkspaceMember).where(
        WorkspaceMember.workspace_id == workspace_id,
        WorkspaceMember.user_id == actor_id,
    )
    member = (await db.scalars(stmt_member)).first()
    if not member:
        raise NotFoundError("Workspace not found", code="WORKSPACE_NOT_FOUND")

    if not can_view_audit_logs(member.role):
        raise ForbiddenError(
            "Only workspace owners and admins can view audit logs",
            code="FORBIDDEN",
        )

    query = select(AuditLog).where(AuditLog.workspace_id == workspace_id)

    if filter_actor_id:
        query = query.where(AuditLog.actor_id == filter_actor_id)
    if filter_action:
        query = query.where(AuditLog.action == filter_action)
    if filter_resource_type:
        query = query.where(AuditLog.resource_type == filter_resource_type)
    if date_from:
        query = query.where(AuditLog.created_at >= date_from)
    if date_to:
        query = query.where(AuditLog.created_at <= date_to)

    query = query.order_by(AuditLog.created_at.desc())

    count_query = select(func.count()).select_from(query.order_by(None).subquery())
    total = await db.scalar(count_query) or 0

    items_query = query.offset(pagination.offset).limit(pagination.size)
    items = list((await db.scalars(items_query)).all())

    return Page.create(items=items, total=total, params=pagination)


